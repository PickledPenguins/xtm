#!/usr/bin/env python3
"""
Test suite for xtm.

Two layers:

  * Unit tests import xtm directly and exercise the pure logic -- YAML
    round-tripping, validation, geometry maths, profile resolution,
    argument parsing, atomic writes and logging setup.

  * Integration tests run xtm as a real subprocess against a temporary
    config directory and a PATH populated with stand-in implementations of
    tmux, xterm, xdotool, wmctrl, xwininfo and xprop. Those stand-ins are
    generated by this file (see FAKE_TOOL_SOURCE) and are driven by a
    small state directory, which lets a test declare "these sessions are
    running, these windows are on screen at these coordinates" and then
    assert on what xtm did about it.

Window placement is verified against a genuine pty pair: the fake tmux
reports the pty's slave device as the session's client tty, xtm writes its
escape sequences there exactly as it would to a real xterm, and the test
reads the raw bytes back off the master side.

No X server, window manager or terminal is required to run any of this.

Usage:
    python3 test_xtm.py                 # run everything
    python3 test_xtm.py -v              # verbose
    python3 -m coverage run test_xtm.py && python3 -m coverage report
"""

